  // Helper for language handling
  let currentLang = 'en';

  function initLang() {
    const saved = localStorage.getItem('transmission_lang');
    if (saved && SUPPORTED.includes(saved)) {
      currentLang = saved;
      return;
    }
    if (window.ShareOS && ShareOS.lang && SUPPORTED.includes(ShareOS.lang)) {
      currentLang = ShareOS.lang;
      return;
    }
    const nav = (navigator.language || navigator.userLanguage || '').toLowerCase().slice(0, 2);
    if (SUPPORTED.includes(nav)) {
      currentLang = nav;
      return;
    }
    currentLang = FALLBACK;
  }

  initLang();

  window.I18N = {
    lang: currentLang,
    supported: SUPPORTED,
    names: {
      pt: 'Português',
      en: 'English',
      de: 'Deutsch'
    },
    setLang(code) {
      if (SUPPORTED.includes(code)) {
        currentLang = code;
        this.lang = code;
        localStorage.setItem('transmission_lang', code);
        document.documentElement.lang = code;
      }
    },
    t(key, vars = {}) {
      const dict = STRINGS[currentLang] || STRINGS[FALLBACK];
      let str = dict[key] || STRINGS[FALLBACK][key] || key;
      for (const [k, v] of Object.entries(vars)) {
        str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), v);
      }
      return str;
    }
  };

  document.documentElement.lang = currentLang;
